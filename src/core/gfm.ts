/**
 * Generic GF(2^m) built from a primitive polynomial, and the cyclic Hamming Code
 * of length 2^m − 1 whose generator is that polynomial. Used for the GF(128) /
 * Hamming(127,120) comparison in Lesson 2-12. Same MSB-first bit convention as cyclic.ts.
 */
import { type Bit, bitsToInt, intToBits, isZeroVector, zeroVector } from './gf2';
import { longDivision } from './cyclic';

export interface Field {
  m: number;
  /** primitive polynomial as an integer bitmask, e.g. x³+x+1 = 0b1011 */
  poly: number;
  size: number; // 2^m
  exp: number[]; // exp[i] = α^i, i = 0 … 2^m − 2
  log: number[]; // log[a] = i, a ≠ 0  (log[0] = −1)
  /** α generates every non-zero element (p(x) is primitive) */
  primitive: boolean;
  /** multiplicative order of α */
  order: number;
}

export function buildField(m: number, poly: number): Field {
  const size = 2 ** m;
  const exp: number[] = [];
  const log = Array.from({ length: size }, () => -1);
  let v = 1;
  let order = 0;
  for (let i = 0; i < size - 1; i++) {
    if (i > 0 && v === 1) break; // α has smaller order
    exp.push(v);
    order++;
    v <<= 1;
    if (v & size) v ^= poly;
  }
  exp.forEach((a, i) => {
    if (log[a] === -1) log[a] = i;
  });
  const primitive = order === size - 1 && v === 1 && new Set(exp).size === size - 1;
  return { m, poly, size, exp, log, primitive, order };
}

export const fieldMul = (F: Field, a: number, b: number): number => (a === 0 || b === 0 ? 0 : F.exp[(F.log[a] + F.log[b]) % (F.size - 1)]);

/** Polynomial bitmask → MSB-first bits of length m+1 */
export const polyMaskToMsb = (poly: number, m: number): Bit[] => intToBits(poly, m + 1);

export interface HammingParams {
  m: number;
  n: number;
  k: number;
  dmin: number;
  rate: number;
  /** extended code */
  nExt: number;
  kExt: number;
  dminExt: number;
  rateExt: number;
  /** parity-check matrix dimensions */
  hRows: number;
  hCols: number;
}

export function hammingParams(m: number): HammingParams {
  const n = 2 ** m - 1;
  const k = n - m;
  return { m, n, k, dmin: 3, rate: k / n, nExt: n + 1, kExt: k, dminExt: 4, rateExt: k / (n + 1), hRows: m, hCols: n };
}

/** Systematic cyclic Hamming Code of length 2^m − 1 generated by the primitive polynomial. */
export class CyclicHamming {
  readonly F: Field;
  readonly g: Bit[];
  readonly n: number;
  readonly k: number;

  constructor(m: number, poly: number) {
    this.F = buildField(m, poly);
    if (!this.F.primitive) throw new Error('polynomial is not primitive');
    this.g = polyMaskToMsb(poly, m);
    this.n = 2 ** m - 1;
    this.k = this.n - m;
  }

  encode(u: readonly Bit[]): Bit[] {
    if (u.length !== this.k) throw new Error(`message must be ${this.k} bits`);
    const shifted = [...u, ...zeroVector(this.F.m)];
    return [...u, ...longDivision(shifted, this.g).remainder];
  }

  syndrome(r: readonly Bit[]): Bit[] {
    return longDivision(r, this.g).remainder;
  }

  /** returns the 1-based left-to-right error position (0 = none) */
  locate(r: readonly Bit[]): number {
    const s = this.syndrome(r);
    if (isZeroVector(s)) return 0;
    const exponent = this.F.log[bitsToInt(s)];
    return this.n - exponent;
  }

  decode(r: readonly Bit[]): { position: number; corrected: Bit[]; syndrome: Bit[] } {
    const position = this.locate(r);
    const corrected = [...r];
    if (position > 0) corrected[position - 1] = (corrected[position - 1] ^ 1) as Bit;
    return { position, corrected, syndrome: this.syndrome(r) };
  }

  /** Row j of the parity-check matrix H = [α^{n−1} … α^1 α^0] (column k is α^{exponent(k)}). Returns #ones per row. */
  hRowWeights(): number[] {
    const rows = Array.from({ length: this.F.m }, () => 0);
    for (let k = 0; k < this.n; k++) {
      const a = this.F.exp[(this.n - 1 - k) % (this.F.size - 1)];
      for (let j = 0; j < this.F.m; j++) if ((a >> j) & 1) rows[j]++;
    }
    return rows;
  }
}

/** Small deterministic PRNG (mulberry32) for reproducible demos and quizzes. */
export function rng(seed: number): () => number {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export const randomBits = (n: number, rand: () => number): Bit[] => Array.from({ length: n }, () => (rand() < 0.5 ? 0 : 1) as Bit);
